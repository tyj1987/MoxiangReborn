"""Generate the separate original Item enum from the fixed legacy Protocol.h.

The generated header is data from the checked original source, never a second
hand-maintained value table. The live modern ItemProtocol remains unchanged.
"""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path


SOURCE_SHA256 = "f0a0c0678bab16b7787bf273d97f31660820e37db6bb3f4f9dec23e104d0e656"
ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SOURCE = ROOT / "墨香【源码】" / "[CC]Header" / "Protocol.h"
DEFAULT_OUTPUT = ROOT / "modern/include/mxh/proto/original_item_profile.hpp"


def extract_item_enum(source: bytes) -> list[tuple[str, int]]:
    """Strip real C/C++ comments before counting enum entries."""
    text = source.decode("latin1")
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"//[^\r\n]*", "", text)
    matches = re.findall(r"\benum\s+MP_PROTOCOL_ITEM\s*\{([^}]*)\}", text, re.DOTALL)
    if len(matches) != 1:
        raise ValueError("expected exactly one MP_PROTOCOL_ITEM enum")
    entries: list[tuple[str, int]] = []
    next_value = 0
    for raw in matches[0].split(","):
        token = raw.strip()
        if not token:
            continue
        match = re.fullmatch(r"(MP_ITEM_[A-Za-z0-9_]+)(?:\s*=\s*(0[xX][0-9A-Fa-f]+|[0-9]+))?", token)
        if not match:
            raise ValueError(f"unsupported Item enumerator: {token!r}")
        name, assigned = match.groups()
        if assigned is not None:
            next_value = int(assigned, 0)
        if any(previous == name for previous, _ in entries):
            raise ValueError(f"duplicate Item enumerator: {name}")
        entries.append((name, next_value))
        next_value += 1
    if not entries or entries[0] != ("MP_ITEM_TOTALINFO_LOCAL", 0) or entries[-1] != ("MP_ITEM_PROTOCOL_MAX", 256):
        raise ValueError("unexpected Item enum boundaries")
    return entries


def render_header(entries: list[tuple[str, int]]) -> bytes:
    lines = [
        "// Generated by modern/tools/generate_original_item_profile.py.",
        f"// Original [CC]Header/Protocol.h SHA-256: {SOURCE_SHA256}",
        "// Separate reference profile; modern ItemProtocol wire IDs are unchanged.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace mxh::proto::original_item {",
        "enum class ItemProtocol : std::uint16_t {",
    ]
    lines.extend(f"    {name} = {value}," for name, value in entries)
    lines.extend(["};", "}  // namespace mxh::proto::original_item", ""])
    return "\n".join(lines).encode("ascii")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="verify the committed header without writing")
    args = parser.parse_args()
    source = args.source.read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(f"original Protocol.h SHA-256 mismatch: {digest}")
    entries = extract_item_enum(source)
    header = render_header(entries)
    if args.check:
        if args.output.read_bytes() != header:
            raise ValueError("generated original Item profile is stale")
    else:
        args.output.write_bytes(header)
    print(f"original Item enum: {len(entries)} entries, BuySyn={dict(entries)['MP_ITEM_BUY_SYN']}, MonsterObtainNotify={dict(entries)['MP_ITEM_MONSTER_OBTAIN_NOTIFY']}, sha256={digest}, check={args.check}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
