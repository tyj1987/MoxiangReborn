// MhFileEx.cpp - Implementation of .bin format reader/writer.
//
// Original source: 墨香【源码】\[Tool]PackingMan\MHFileEx.cpp
// Algorithm reproduced verbatim from the original code's CMHFileEx::OpenBin().
//
// IMPORTANT real-file layout (from OpenBin()):
//   [12 bytes MHFILE_HEADER]
//   [1 byte CRC1]                                  <- always present
//   [_RXMSO_ defined: +1 byte extra CRC]
//   [_MSO50_ defined: +3 bytes extra CRC]
//   [dwDataSize bytes encrypted payload]
//   [_RXMSO_ defined: +1 byte extra CRC]
//   [_MSO50_ defined: +2 bytes extra CRC]
//   [1 byte CRC2]                                  <- always present
//
// CheckHeader() is COMMENTED OUT in the original (returns TRUE early),
// so dwVersion is NOT validated. Only dwDataSize is trusted.
// We replicate that behavior to stay 1:1 compatible.

#include "mxh/compat/mh_file_ex.hpp"

